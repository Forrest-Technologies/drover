"""Computes every contrast pair of every theme file and writes docs/design/themes/contrast.md.

A report for issue 421. The build enforces these pairs in ThemeGates (issue 423), tests in ThemeGateTests.
Run: python3 scripts/themes/contrast.py
"""

import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))

from color import ratio  # noqa: E402
from themes import ACCENTS, HEADS, HUES, ROOT, STATUS, SURFACES, TEXT, VISORS, load, modes  # noqa: E402

TARGET = ROOT / "docs/design/themes/contrast.md"


def lowest(colors, foreground, backgrounds):
    worst = min(backgrounds, key=lambda background: ratio(colors[foreground], colors[background]))
    return ratio(colors[foreground], colors[worst]), worst


def rows(theme):
    for mode in modes(theme):
        colors = theme[mode]["color"]
        for foreground in TEXT + ACCENTS + STATUS:
            value, surface = lowest(colors, foreground, SURFACES)
            yield mode, foreground, "every surface", value, surface, 4.5
        value, surface = min((lowest(colors, hue, SURFACES) for hue in HUES), key=lambda pair: pair[0])
        yield mode, "hue-0 to hue-11", "every surface", value, surface, 4.5
        value, surface = lowest(colors, "text-3", SURFACES)
        yield mode, "control edge (text-3)", "every surface", value, surface, 3
        yield mode, "on-accent", "ember", ratio(colors["on-accent"], colors["ember"]), "ember", 4.5
        for visor in VISORS:
            value, head = lowest(colors, visor, HEADS)
            yield mode, visor, "every head", value, head, 3


def main():
    lines = [
        "# Theme contrast, computed",
        "",
        "Generated by `scripts/themes/contrast.py` from the theme files in `src/Drover.Presentation/Theme/Themes`.",
        "Each row is the lowest ratio of the pair across everything it must stand on, with the WCAG formula the",
        "contrast tests use. Text and status need 4.5:1 on every surface, control edges 3:1, the visor 3:1 against",
        "every head at rest, lit and failed. The build enforces these pairs with `ThemeGates`, whose tests run over every file.",
        "",
    ]
    failures = 0
    for theme in load():
        lines += [f"## {theme['name']}", "", "| Mode | Foreground | On | Lowest | Where | Needs |", "| --- | --- | --- | --- | --- | --- |"]
        for mode, foreground, against, value, where, needs in rows(theme):
            failures += value < needs
            mark = "" if value >= needs else " (falls short)"
            lines.append(f"| {mode} | `{foreground}` | {against} | {value:.2f}{mark} | `{where}` | {needs} |")
        lines.append("")
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text("\n".join(lines))
    print(f"{failures} pairs fall short; wrote {TARGET.relative_to(ROOT)}")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
